"""Copy legacy resident images to private storage and generate reviewed MySQL SQL.

This utility never connects to the database and never deletes source files. Export
family member IDs/references to CSV first, review the manifest, then execute the
generated SQL separately.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import os
import re
import shutil
import sys
import uuid
from pathlib import Path


LEGACY_REFERENCE = re.compile(r"^/uploads/residents/([0-9a-fA-F-]{36}\.jpg)$")
PRIVATE_REFERENCE = re.compile(r"^resident:([0-9a-fA-F-]{36}\.jpg)$")
MAX_BYTES = 10 * 1024 * 1024


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def image_extension(path: Path) -> str:
    with path.open("rb") as stream:
        header = stream.read(8)
    if header[:3] == b"\xff\xd8\xff":
        return ".jpg"
    if header == b"\x89PNG\r\n\x1a\n":
        return ".png"
    raise ValueError("file nguồn không có JPEG hoặc PNG signature hợp lệ")


def valid_filename(filename: str) -> bool:
    try:
        return str(uuid.UUID(filename[:-4])) == filename[:-4].lower() and filename.lower().endswith(".jpg")
    except (ValueError, AttributeError):
        return False


def sql_text(successes: list[dict[str, str]]) -> str:
    lines = [
        "-- Generated by migrate-resident-images-private.py; review before execution.",
        "START TRANSACTION;",
        "CREATE TABLE IF NOT EXISTS resident_image_private_migration_backup (",
        "    member_id BIGINT NOT NULL PRIMARY KEY,",
        "    old_reference VARCHAR(500) NOT NULL,",
        "    new_reference VARCHAR(500) NOT NULL,",
        "    sha256 CHAR(64) NOT NULL,",
        "    size_bytes BIGINT NOT NULL,",
        "    migrated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)",
        ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;",
    ]
    for row in successes:
        member_id = int(row["member_id"])
        old = row["old_reference"].replace("'", "''")
        new = row["new_reference"].replace("'", "''")
        lines.extend([
            "INSERT IGNORE INTO resident_image_private_migration_backup ",
            "    (member_id, old_reference, new_reference, sha256, size_bytes)",
            f"VALUES ({member_id}, '{old}', '{new}', '{row['sha256']}', {row['size_bytes']});",
            "UPDATE family_members",
            f"SET registration_face_image_path = '{new}'",
            f"WHERE id = {member_id} AND registration_face_image_path = '{old}';",
        ])
    lines.extend([
        "COMMIT;",
        "-- Postcheck: both counts must be zero.",
        "SELECT COUNT(*) AS legacy_references FROM family_members",
        "WHERE registration_face_image_path LIKE '/uploads/residents/%';",
        "SELECT COUNT(*) AS migrated_reference_mismatches",
        "FROM resident_image_private_migration_backup b",
        "JOIN family_members f ON f.id = b.member_id",
        "WHERE BINARY f.registration_face_image_path <> BINARY b.new_reference;",
        "-- Rollback mapping (run only after incident review):",
        "-- UPDATE family_members f JOIN resident_image_private_migration_backup b ON b.member_id=f.id",
        "-- SET f.registration_face_image_path=b.old_reference",
        "-- WHERE BINARY f.registration_face_image_path=BINARY b.new_reference;",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input-csv", required=True, type=Path)
    parser.add_argument("--legacy-root", required=True, type=Path)
    parser.add_argument("--private-root", required=True, type=Path)
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--sql-output", required=True, type=Path)
    args = parser.parse_args()

    legacy_root = args.legacy_root.resolve()
    private_root = args.private_root.resolve()
    private_root.mkdir(parents=True, exist_ok=True)
    results: list[dict[str, str]] = []
    failures = 0

    with args.input_csv.open("r", encoding="utf-8-sig", newline="") as source:
        reader = csv.DictReader(source)
        required = {"id", "registration_face_image_path"}
        if not reader.fieldnames or not required.issubset(reader.fieldnames):
            raise ValueError("CSV phải có cột id và registration_face_image_path")
        for input_row in reader:
            member_id = input_row["id"].strip()
            old_reference = input_row["registration_face_image_path"].strip()
            result = {"member_id": member_id, "old_reference": old_reference,
                      "new_reference": "", "size_bytes": "", "sha256": "", "status": ""}
            try:
                int(member_id)
                if PRIVATE_REFERENCE.fullmatch(old_reference):
                    result["new_reference"] = old_reference
                    result["status"] = "ALREADY_PRIVATE"
                    results.append(result)
                    continue
                match = LEGACY_REFERENCE.fullmatch(old_reference)
                if not match or not valid_filename(match.group(1)):
                    raise ValueError("reference legacy không đúng mẫu")
                legacy_filename = match.group(1).lower()
                source_path = legacy_root / legacy_filename
                if source_path.parent.resolve() != legacy_root or source_path.is_symlink() or not source_path.is_file():
                    raise ValueError("file nguồn không tồn tại hoặc không an toàn")
                size = source_path.stat().st_size
                if size <= 0 or size > MAX_BYTES:
                    raise ValueError("kích thước file nguồn không hợp lệ")
                extension = image_extension(source_path)
                filename = legacy_filename[:-4] + extension
                destination = private_root / filename
                source_hash = sha256(source_path)
                if destination.exists():
                    if (destination.is_symlink() or not destination.is_file()
                            or image_extension(destination) != extension or sha256(destination) != source_hash):
                        raise ValueError("file đích tồn tại nhưng checksum không khớp")
                else:
                    temporary = private_root / f".resident-migration-{uuid.uuid4()}.tmp"
                    try:
                        shutil.copyfile(source_path, temporary)
                        if sha256(temporary) != source_hash:
                            raise ValueError("checksum sau copy không khớp")
                        os.replace(temporary, destination)
                    finally:
                        temporary.unlink(missing_ok=True)
                result.update(new_reference=f"resident:{filename}", size_bytes=str(size),
                              sha256=source_hash, status="COPIED_AND_VERIFIED")
            except Exception as error:  # manifest must retain every failed row
                failures += 1
                result["status"] = "ERROR: " + str(error)
            results.append(result)

    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    with args.manifest.open("w", encoding="utf-8-sig", newline="") as output:
        writer = csv.DictWriter(output, fieldnames=[
            "member_id", "old_reference", "new_reference", "size_bytes", "sha256", "status"])
        writer.writeheader()
        writer.writerows(results)

    if failures:
        args.sql_output.unlink(missing_ok=True)
        print(f"Migration preflight failed: {failures} row(s). Manifest written; SQL not generated.",
              file=sys.stderr)
        return 1
    successes = [row for row in results if row["status"] == "COPIED_AND_VERIFIED"]
    args.sql_output.write_text(sql_text(successes), encoding="utf-8")
    print(f"Verified {len(successes)} image(s); SQL was not executed: {args.sql_output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
